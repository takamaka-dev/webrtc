import json, sys
c1, vec, out = sys.argv[1], sys.argv[2], sys.argv[3]
rows = []
for line in open(c1):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    k, c, h = line.split()
    rows.append((k, c, h))
d = json.load(open(vec))['group6_sframe']
r = d['rfc9605_c3_suite5']
u = d['units']
L = []
L.append('// GENERATED by gen_vectors.py from')
L.append('//   Messages/src/test/resources/call/rfc9605_c1_headers.txt (RFC 9605 Appendix C.1, %d rows) and' % len(rows))
L.append('//   rschat-docs/security/vectors/call_vectors_v1.json group6_sframe (Java reference generator).')
L.append('// Do not edit by hand.')
L.append('struct C1Row { uint64_t kid; uint64_t ctr; const char* header; };')
L.append('constexpr C1Row kRfc9605C1[] = {')
for k, c, h in rows:
    L.append('    {0x%sULL, 0x%sULL, "%s"},' % (k, c, h))
L.append('};')
L.append('struct C3Suite5 { uint64_t kid; uint64_t ctr; const char* base_key; const char* key_label; const char* salt_label;')
L.append('  const char* secret; const char* key; const char* salt; const char* metadata; const char* nonce; const char* pt; const char* ct; };')
L.append('constexpr C3Suite5 kRfc9605C3Suite5 = {0x%sULL, 0x%sULL, "%s", "%s", "%s", "%s", "%s", "%s", "%s", "%s", "%s", "%s"};' % (
    r['kid'], r['ctr'], r['base_key'], r['sframe_key_label'], r['sframe_salt_label'], r['sframe_secret'], r['sframe_key'],
    r['sframe_salt'], r['metadata'], r['nonce'], r['pt'], r['ct']))
L.append('struct UnitCase { const char* codec; size_t prefix_len; uint64_t ctr; const char* frame; const char* header; const char* nonce; const char* aad; const char* unit; };')
L.append('constexpr uint32_t kUnitsLegIndex = %d;' % u['leg_index'])
L.append('constexpr uint64_t kUnitsEpoch = %d;' % u['epoch'])
L.append('constexpr uint64_t kUnitsKid = 0x%sULL;' % u['kid'])
L.append('constexpr const char* kUnitsBaseKey = "%s";' % u['base_key'])
L.append('constexpr const char* kUnitsSecret = "%s";' % u['sframe_secret'])
L.append('constexpr const char* kUnitsKey = "%s";' % u['sframe_key'])
L.append('constexpr const char* kUnitsSalt = "%s";' % u['sframe_salt'])
L.append('constexpr UnitCase kUnitCases[] = {')
for c in u['cases']:
    L.append('    {"%s", %d, %d, "%s", "%s", "%s", "%s", "%s"},' % (c['codec'], c['prefix_len'], c['ctr'], c['frame'], c['header'], c['nonce'], c['aad'], c['unit']))
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
print(len(rows), 'C1 rows;', len(u['cases']), 'unit cases;', 'h264:', u['h264']['status'])
